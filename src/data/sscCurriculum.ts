export interface LevelThreshold {
  name: string;
  minXp: number;
}

export const LEVELS: LevelThreshold[] = [
  { name: 'Beginner', minXp: 0 },
  { name: 'Rookie', minXp: 300 },
  { name: 'Scholar', minXp: 900 },
  { name: 'Expert', minXp: 2000 },
  { name: 'Master', minXp: 4000 },
  { name: 'SSC Champion', minXp: 7500 },
];

export function computeLevel(xp: number): {
  current: LevelThreshold;
  next: LevelThreshold | null;
  progressPct: number;
} {
  let current = LEVELS[0];
  let next: LevelThreshold | null = LEVELS[1];
  for (let i = 0; i < LEVELS.length; i++) {
    if (xp >= LEVELS[i].minXp) {
      current = LEVELS[i];
      next = LEVELS[i + 1] ?? null;
    }
  }
  if (!next) {
    return { current, next: null, progressPct: 100 };
  }
  const span = next.minXp - current.minXp;
  const gained = xp - current.minXp;
  return {
    current,
    next,
    progressPct: Math.min(100, Math.max(0, Math.round((gained / span) * 100))),
  };
}

